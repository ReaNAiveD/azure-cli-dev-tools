EXCEPTION_SUMMARIZATION_PROMPT = """
You are a helpful Python Static Analysis Assistant. You will receive:
1. A Python Code Snippet
2. A JSON list describe all related call Usage in the Code Snippet
Your task is to analyze the types of exceptions that could potentially be raised during execution.

---Output Format---
Return a JSON list of probable raised exception types, each item is a JSON object with "name" and "package"(optional) field
* "name": type name
* "package": The package or module the exception belongs to (e.g., "builtins", "requests", "package.name")
* "description": A concise explanation of what the exception represents
* "condition": A detailed explanation of the specific condition under which the exception might be raised, based on the arguments and context of the call in the code snippet
**IMPORTANT:**
* If an exception is explicitly caught and handled in the code snippet, it should be excluded from the output.
* The "condition" field should describe the specific scenario under which the exception might be raised. This should be derived primarily from the call_usage data, but must be updated based on the actual context in the code_snippet. Specifically:
    * If the arguments in the code_snippet override or specialize the usage pattern described in call_usage, update the "condition" to reflect the actual argument values.
    * If the call described in call_usage is only invoked under a specific condition in the code_snippet (e.g., inside an if block, guarded by a try-except, or dependent on a variable state), incorporate that condition into the "condition" field.
* Use the actual argument values from the code_snippet to make the "condition" as specific, contextual, and informative as possible. Avoid generic phrases when concrete values or logic are available.

---Example Output---

[
    {{
        "name": "ValueError",
        "package": "builtins",
        "description": "Raised when a function receives an argument of the correct type but an inappropriate value.",
        "condition": "When the 'mode' argument is set to 'invalid_mode', which is not supported by the function."
    }},
    {{
        "name": "KeyError",
        "package": "builtins",
        "description": "Raised when a dictionary key is not found.",
        "condition": "When accessing 'config['timeout']' and the 'timeout' key is missing from the 'config' dictionary."
    }}
]


---Input---
Code Snippet:
{code_snippet}

Related Call Usage:
{call_usage}
"""


def logic_summarize(code_snippet, call_usage, client=None):
    if not client:
        client = chat_client_4o_mini()
    resp = client.complete(
        messages=[
            ChatRequestSystemMessage(
                content=LOGIC_SUMMARIZATION_PROMPT.format(
                    code_snippet=code_snippet and code_snippet[:50000],
                    call_usage=json.dumps(call_usage)[:50000],
                ),
            ),
            ChatRequestUserMessage(
                content='Please give the result in correct format.'
            )
        ],
        max_tokens=1000,
    )

    content = resp.choices[0].message.content
    return content

